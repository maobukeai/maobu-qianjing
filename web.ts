export const STANDALONE_SESSION_COOKIE = "maobu_session";
export const STANDALONE_SESSION_HEADER = "X-Maobu-Session";

const SPA_SECURITY_HEADERS = {
    "Content-Security-Policy": "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self' http://127.0.0.1:* ws://127.0.0.1:* ipc: http://ipc.localhost https://ipc.localhost; object-src 'none'; base-uri 'self'; frame-ancestors 'none'",
    "X-Content-Type-Options": "nosniff",
    "X-Frame-Options": "DENY",
} as const;

const CARD_SECURITY_HEADERS = {
    "Content-Security-Policy": "default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; frame-ancestors 'none'; form-action 'none'",
    "X-Content-Type-Options": "nosniff",
    "X-Frame-Options": "DENY",
} as const;

const API_SECURITY_HEADERS = {
    "Content-Security-Policy": "default-src 'none'; frame-ancestors 'none'",
    "X-Content-Type-Options": "nosniff",
    "X-Frame-Options": "DENY",
} as const;

function withSecurityHeaders(response: Response, kind: "spa" | "card" | "api"): Response {
    const defaults = kind === "spa" ? SPA_SECURITY_HEADERS : kind === "card" ? CARD_SECURITY_HEADERS : API_SECURITY_HEADERS;
    try {
        for (const [k, v] of Object.entries(defaults)) {
            if (!response.headers.has(k)) response.headers.set(k, v);
        }
        return response;
    } catch {
        const headers = new Headers(response.headers);
        for (const [k, v] of Object.entries(defaults)) {
            if (!headers.has(k)) headers.set(k, v);
        }
        return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
    }
}

function parseCookieValue(cookieHeader: string | null, name: string): string | null {
    if (!cookieHeader) return null;
    for (const part of cookieHeader.split(";")) {
        const eq = part.indexOf("=");
        if (eq === -1) continue;
        if (part.slice(0, eq).trim() === name) {
            return part.slice(eq + 1).trim();
        }
    }
    return null;
}

export function isStandaloneRequestAuthorized(req: Request, accessToken: string): boolean {
    const auth = req.headers.get("authorization");
    if (auth?.startsWith("Bearer ") && matchesSession(auth.slice(7).trim(), accessToken)) return true;
    if (matchesSession(req.headers.get(STANDALONE_SESSION_HEADER), accessToken)) return true;
    if (matchesSession(parseCookieValue(req.headers.get("cookie"), STANDALONE_SESSION_COOKIE), accessToken)) return true;
    return false;
}
